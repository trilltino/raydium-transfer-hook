// Generates src/generated/environments.ts from the repository's environment files, so the browser
// never reads the repo JSON at run time and holds only public program ids. Run by `predev` / `prebuild`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'generated', 'environments.ts');

function pick(file) {
  const raw = JSON.parse(readFileSync(join(root, 'environments', file), 'utf8'));
  const need = (value, what) => {
    if (typeof value !== 'string' || !value) throw new Error(`${file}: missing ${what}`);
    return value;
  };
  return {
    name: need(raw.name, 'name'),
    cluster: need(raw.cluster, 'cluster'),
    rpcUrl: need(raw.rpc_url, 'rpc_url'),
    cpmmProgramId: need(raw.programs?.cpmm, 'programs.cpmm'),
    clmmProgramId: need(raw.programs?.clmm, 'programs.clmm'),
    fairLaunchProgramId: need(raw.programs?.templates?.fair_launch, 'programs.templates.fair_launch'),
  };
}

const environments = [pick('localnet.json'), pick('devnet.json')];
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by scripts/generate-environments.mjs from environments/*.json. Do not edit.\n` +
    `import type { HookEnvironment } from '@raydium-transfer-hook/client';\n\n` +
    `export const ENVIRONMENTS: readonly HookEnvironment[] = ${JSON.stringify(environments, null, 2)};\n`
);
console.log(`wrote ${out}`);
